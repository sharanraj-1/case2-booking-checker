"""Download results as .xlsx (summary sheet + findings sheet + carrier options)."""

from __future__ import annotations

import io

import pandas as pd

import engine
from engine import format_date, num

STATUS_EMOJI = {"Blocked": "🔴", "Ready with warnings": "🟠", "Ready": "🟢"}


def route(r: engine.BookingResult) -> str:
    b = r.booking
    return f"{b.get('origin_city') or '?'} → {b.get('dest_city') or '?'}, {b.get('dest_country') or '?'}"


def summary_rows(results: list[engine.BookingResult]) -> list[dict]:
    return [{
        "Booking ID": r.booking_id,
        "Seller": r.booking.get("seller") or "",
        "Route": route(r),
        "Status": f"{STATUS_EMOJI.get(r.status, '')} {r.status}",
        "Red": r.red_count + r.data_count,
        "Amber": r.amber_count,
        "Carrier": r.recommendation or "—",
        "Cost (£)": r.total_cost,
        "ETA": format_date(r.eta),
    } for r in results]


def invoice_xlsx(r: engine.BookingResult) -> bytes:
    """Draft commercial invoice following the business.gov.uk checklist. Blanks marked [ADD] are for the seller."""
    import openpyxl
    from openpyxl.styles import Alignment, Font, PatternFill

    import knowledge
    b, opt = r.booking, r.chosen_option
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Commercial invoice (draft)"
    bold, add = Font(bold=True), PatternFill("solid", fgColor="FFF4CC")
    ws.append(["COMMERCIAL INVOICE (DRAFT)"])
    ws["A1"].font = Font(bold=True, size=14)
    header = [
        ("Invoice number", "[ADD]"), ("Invoice date", format_date(engine.today_london())),
        ("Seller (exporter)", f"{b.get('seller') or '[ADD]'} — [ADD full address and contact details]"),
        ("Seller GB EORI", "[ADD GB…]"),
        ("Buyer (importer)", "[ADD name, address and contact details]"), ("Buyer EU EORI", "[ADD]"),
        ("Consignee (if different from buyer)", "[ADD or 'Same as buyer']"),
        ("Related paperwork (proforma / PO / contract no. and date)", "[ADD]"),
        ("Incoterms", "[ADD e.g. DAP or DDP]"), ("Currency", "GBP"), ("Method of payment", "[ADD]"),
        ("Transport", f"Road freight, {b.get('origin_city') or '?'} → {b.get('dest_city') or '?'}, {b.get('dest_country') or '?'}"
                      + (f", {opt.carrier} ({opt.service})" if opt else "")),
        ("Packages", f"{num(r.item_cartons) if r.item_cartons is not None else '[ADD]'} boxes on "
                     f"{num(b.get('pallets')) if b.get('pallets') else '[ADD]'} pallets; marks: box 1 to "
                     f"{num(r.item_cartons) if r.item_cartons else 'N'} with invoice number"),
    ]
    for k, v in header:
        ws.append([k, v])
        ws.cell(ws.max_row, 1).font = bold
        if "[ADD" in str(v):
            ws.cell(ws.max_row, 2).fill = add
    ws.append([])
    cols = ["Description (plain English)", "HS code", "Country of origin", "Quantity", "Unit price (GBP)",
            "Line total (GBP)", "Net weight (kg)", "Boxes"]
    ws.append(cols)
    for c in ws[ws.max_row]:
        c.font = bold
    for it in r.items:
        q, p, u = it.get("qty"), it.get("unit_price"), it.get("unit_kg")
        ws.append([it.get("description"), it.get("hs_code") or "[ADD]", it.get("coo") or "[ADD]", q, p,
                   round(q * p, 2) if q is not None and p is not None else None,
                   round(q * u, 3) if q is not None and u is not None else None, it.get("cartons")])
    ws.append([])
    totals = [("Total value of goods (GBP)", b.get("declared_value")), ("Total net weight (kg)", r.net_kg),
              ("Total gross weight (kg)", b.get("gross_kg")),
              ("Freight (GBP)", r.total_cost), ("Insurance / other charges (GBP)", "[ADD if charged]")]
    for k, v in totals:
        ws.append([k, v])
        ws.cell(ws.max_row, 1).font = bold
    if any(i.get("coo") == "United Kingdom" for i in r.items):
        ws.append([])
        ws.append(["Statement on origin (UK-origin lines only)"])
        ws.cell(ws.max_row, 1).font = bold
        ws.append([knowledge.country_rules(r)["statement_on_origin"]])
        ws.cell(ws.max_row, 1).alignment = Alignment(wrap_text=True)
    ws.append([])
    ws.append(["Draft generated by Pallet Pre-Flight from your booking. Fill every [ADD] before printing. "
               f"Checklist: {knowledge.INVOICE_GUIDE}"])
    for col, w in zip("ABCDEFGH", (46, 52, 18, 10, 16, 16, 16, 8)):
        ws.column_dimensions[col].width = w
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def to_xlsx(results: list[engine.BookingResult]) -> bytes:
    summary = pd.DataFrame([{
        **{k: v for k, v in row.items() if k not in ("Red", "Amber", "Status", "Carrier", "Cost (£)", "ETA")},
        "Status": r.status,
        "Red (must fix)": r.red_count,
        "Data issues": r.data_count,
        "Amber (warnings)": r.amber_count,
        "Advisory": r.count("Advisory"),
        "Rules passed": f"{len(r.rules_passed)}/10",
        "Recommended carrier": r.recommendation or "—",
        "Cost (£)": r.total_cost,
        "Collection date": format_date(r.collection_date),
        "Estimated delivery": format_date(r.eta),
        "Why this carrier": r.reason,
    } for row, r in zip(summary_rows(results), results)])
    findings = pd.DataFrame([{
        "Booking ID": r.booking_id, "Rule": f.rule_id, "Severity": f.severity, "SKU": f.sku or "",
        "What's wrong": f.message, "How to fix": f.fix,
    } for r in results for f in r.findings], columns=["Booking ID", "Rule", "Severity", "SKU", "What's wrong", "How to fix"])
    options = pd.DataFrame([{
        "Booking ID": r.booking_id, "Carrier": o.carrier, "Service": o.service,
        "Recommended": "Yes" if o.carrier == r.recommendation else "",
        "Eligible": {True: "Yes", False: "No", None: "Unknown"}[o.eligible],
        "Cost (£)": o.cost, "Pallets needed": o.pallets_needed, "Cost if re-palletised (£)": o.cost_if_repalletised,
        "Transit (working days)": o.transit_days, "On time %": o.on_time, "Max kg/pallet": o.max_kg,
        "Est. delivery": format_date(o.eta), "Excluded because": o.excluded_reason,
    } for r in results for o in r.options])
    buf = io.BytesIO()
    with pd.ExcelWriter(buf, engine="openpyxl") as xw:
        summary.to_excel(xw, sheet_name="Summary", index=False)
        findings.to_excel(xw, sheet_name="Findings", index=False)
        options.to_excel(xw, sheet_name="Carrier options", index=False)
        for ws in xw.book.worksheets:
            for col in ws.columns:
                width = max(len(str(c.value or "")) for c in col[:50])
                ws.column_dimensions[col[0].column_letter].width = min(max(10, width + 2), 70)
    return buf.getvalue()
